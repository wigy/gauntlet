/**
 * Draws every built-in and imported arcade level to docs/levels/<set>/ and rewrites the level catalog in README.md
 * (between the CATALOG_START and CATALOG_END markers): small pictures that link to the full-sized ones.
 *
 *   npm run catalog
 *
 * Needs both arcade imports (npm run import:g1, npm run import:g2) so that a machine without them can't drop those
 * sets from the catalog. Arcade maps only hold walls and exits, so their monsters and items come from populate(), with
 * the same seed as a copy in the editor (LevelLibrary.get). Each game places them differently, from its own seed.
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import jpeg from 'jpeg-js';
import { PNG } from 'pngjs';
import type { ItemKind } from '../src/core/defs';
import { Tile, isEmptyLevel, isWallLike, levelTitle, mod, parseLevel, populate, tileAt } from '../src/core/level';
import type { LevelData } from '../src/core/level';
import { BUILTIN_LEVELS } from '../src/levels/builtin';

/** Tile size in the full-sized pictures, thumbnail width in the files and as shown in the README (sharp on HiDPI). */
const TILE = 24;
const THUMB_FILE = 240;
const THUMB_SHOWN = 120;
const COLUMNS = 6;
const JPEG_QUALITY = 80;

const CATALOG_START = '<!-- level-catalog:start (generated by npm run catalog) -->';
const CATALOG_END = '<!-- level-catalog:end -->';
const SPRITES = 'public/sprites';
const OUT = 'docs/levels';

/** Same order as WALL_VARIANTS in src/render/sprites.ts, so a level has the wall colour it has in the game. */
const WALL_VARIANTS: [string, number][] = [['wall-orange', 0], ['wall-teal', 0], ['wall-orange', 230], ['wall-orange', -25], ['wall-teal', 90], ['wall-orange', 60]];
const ITEM_SPRITES: Record<ItemKind, string> = {
  food: 'food', cider: 'cider', potion: 'potion', key: 'key', treasure: 'treasure-gold', amulet: 'amulet', poison: 'poison', it: 'it',
};

type Rgb = [number, number, number];

/** RGBA, 8 bits per channel. */
interface Image {
  w: number;
  h: number;
  data: Uint8Array;
}

function newImage(w: number, h: number): Image {
  return { w, h, data: new Uint8Array(w * h * 4) };
}

/** Area-averaging downscale, with alpha-weighted colours so transparent pixels don't bleed into the edges. */
function shrink(src: Image, w: number, h: number): Image {
  const out = newImage(w, h);
  for (let y = 0; y < h; y++) {
    const sy0 = Math.floor((y * src.h) / h);
    const sy1 = Math.max(sy0 + 1, Math.floor(((y + 1) * src.h) / h));
    for (let x = 0; x < w; x++) {
      const sx0 = Math.floor((x * src.w) / w);
      const sx1 = Math.max(sx0 + 1, Math.floor(((x + 1) * src.w) / w));
      let r = 0, g = 0, b = 0, a = 0;
      for (let sy = sy0; sy < sy1; sy++) {
        for (let sx = sx0; sx < sx1; sx++) {
          const i = (sy * src.w + sx) * 4;
          const alpha = src.data[i + 3];
          r += src.data[i] * alpha;
          g += src.data[i + 1] * alpha;
          b += src.data[i + 2] * alpha;
          a += alpha;
        }
      }
      const o = (y * w + x) * 4;
      if (a > 0) {
        out.data[o] = r / a;
        out.data[o + 1] = g / a;
        out.data[o + 2] = b / a;
        out.data[o + 3] = a / ((sy1 - sy0) * (sx1 - sx0));
      }
    }
  }
  return out;
}

/** The colour matrix of CSS hue-rotate(), which the game uses for its wall variants. */
function hueRotated(src: Image, degrees: number): Image {
  if (degrees === 0) return src;
  const c = Math.cos((degrees * Math.PI) / 180);
  const s = Math.sin((degrees * Math.PI) / 180);
  const m = [
    0.213 + c * 0.787 - s * 0.213, 0.715 - c * 0.715 - s * 0.715, 0.072 - c * 0.072 + s * 0.928,
    0.213 - c * 0.213 + s * 0.143, 0.715 + c * 0.285 + s * 0.14, 0.072 - c * 0.072 - s * 0.283,
    0.213 - c * 0.213 - s * 0.787, 0.715 - c * 0.715 + s * 0.715, 0.072 + c * 0.928 + s * 0.072,
  ];
  const out = newImage(src.w, src.h);
  for (let i = 0; i < src.data.length; i += 4) {
    const [r, g, b] = [src.data[i], src.data[i + 1], src.data[i + 2]];
    out.data[i] = Math.max(0, Math.min(255, m[0] * r + m[1] * g + m[2] * b));
    out.data[i + 1] = Math.max(0, Math.min(255, m[3] * r + m[4] * g + m[5] * b));
    out.data[i + 2] = Math.max(0, Math.min(255, m[6] * r + m[7] * g + m[8] * b));
    out.data[i + 3] = src.data[i + 3];
  }
  return out;
}

const spriteCache = new Map<string, Image>();

/** A sprite from public/sprites at the given size (hue-rotated if asked), cached. */
function sprite(name: string, size: number, hue = 0): Image {
  const key = `${name}/${size}/${hue}`;
  let img = spriteCache.get(key);
  if (!img) {
    const png = PNG.sync.read(readFileSync(join(SPRITES, `${name}.png`)));
    img = hueRotated(shrink({ w: png.width, h: png.height, data: png.data }, size, size), hue);
    spriteCache.set(key, img);
  }
  return img;
}

/** Alpha-blend one pixel; `a` is 0..1. Out-of-bounds pixels are skipped. */
function plot(img: Image, x: number, y: number, [r, g, b]: Rgb, a: number): void {
  if (x < 0 || y < 0 || x >= img.w || y >= img.h) return;
  const i = (y * img.w + x) * 4;
  img.data[i] += (r - img.data[i]) * a;
  img.data[i + 1] += (g - img.data[i + 1]) * a;
  img.data[i + 2] += (b - img.data[i + 2]) * a;
  img.data[i + 3] = 255;
}

function rect(img: Image, x: number, y: number, w: number, h: number, color: Rgb, a: number): void {
  for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) plot(img, x + i, y + j, color, a);
}

/** A disc with a soft rim, or a ring when `inner` is above 0 (both are radii in pixels). */
function disc(img: Image, cx: number, cy: number, r: number, color: Rgb, a: number, inner = 0): void {
  for (let y = Math.floor(cy - r); y <= cy + r; y++) {
    for (let x = Math.floor(cx - r); x <= cx + r; x++) {
      const d = Math.hypot(x + 0.5 - cx, y + 0.5 - cy);
      const cover = Math.min(1, Math.max(0, r - d + 0.5), inner ? Math.max(0, d - inner + 0.5) : 1);
      if (cover > 0) plot(img, x, y, color, a * cover);
    }
  }
}

function blit(img: Image, s: Image, x: number, y: number): void {
  for (let j = 0; j < s.h; j++) {
    for (let i = 0; i < s.w; i++) {
      const k = (j * s.w + i) * 4;
      if (s.data[k + 3]) plot(img, x + i, y + j, [s.data[k], s.data[k + 1], s.data[k + 2]], s.data[k + 3] / 255);
    }
  }
}

/** A sprite centred on a tile, `scale` tiles wide. */
function place(img: Image, name: string, tx: number, ty: number, scale: number): void {
  const size = Math.round(TILE * scale);
  blit(img, sprite(name, size), Math.round((tx + 0.5) * TILE - size / 2), Math.round((ty + 0.5) * TILE - size / 2));
}

function drawTile(img: Image, level: LevelData, n: number, x: number, y: number): void {
  const t = tileAt(level, x, y) as Tile;
  const [px, py] = [x * TILE, y * TILE];
  const [cx, cy] = [px + TILE / 2, py + TILE / 2];
  const edge = Math.max(1, Math.round(TILE * 0.07));
  const isWall = (dx: number, dy: number) => isWallLike(tileAt(level, x + dx, y + dy));

  if (isWallLike(t)) {
    const [name, hue] = WALL_VARIANTS[mod(n - 1, WALL_VARIANTS.length)];
    blit(img, sprite(name, TILE, hue), px, py);
    // Bevels on the edges facing open floor, as in the game, so runs of wall read as solid blocks.
    if (!isWall(0, -1)) rect(img, px, py, TILE, edge, [255, 240, 215], 0.28);
    if (!isWall(-1, 0)) rect(img, px, py, edge, TILE, [255, 240, 215], 0.14);
    if (!isWall(1, 0)) rect(img, px + TILE - edge, py, edge, TILE, [0, 0, 0], 0.3);
    if (!isWall(0, 1)) rect(img, px, py + Math.round(TILE * 0.78), TILE, TILE - Math.round(TILE * 0.78), [10, 6, 16], 0.5);
    if (t === Tile.Breakable) {
      for (let i = 3; i < TILE - 3; i++) {
        plot(img, px + i, py + i, [255, 235, 190], 0.75);
        plot(img, px + TILE - 1 - i, py + i, [255, 235, 190], 0.75);
      }
    } else if (t === Tile.TrapWall) {
      rect(img, px + 3, py + 3, TILE - 6, TILE - 6, [255, 80, 200], 0.3);
    }
    return;
  }

  blit(img, sprite('floor', TILE), px, py);
  rect(img, px, py, TILE, TILE, [8, 6, 14], 0.38);
  if (isWall(0, -1)) rect(img, px, py, TILE, edge * 2, [0, 0, 0], 0.3);
  if (isWall(-1, 0)) rect(img, px, py, edge * 2, TILE, [0, 0, 0], 0.22);

  if (t === Tile.Door) {
    blit(img, sprite('door', TILE), px, py);
  } else if (t === Tile.Exit) {
    disc(img, cx, cy, TILE * 0.46, [26, 168, 216], 1);
    disc(img, cx, cy, TILE * 0.32, [6, 36, 58], 1);
    disc(img, cx, cy, TILE * 0.3, [150, 235, 255], 0.8, TILE * 0.2);
    disc(img, cx, cy, TILE * 0.1, [0, 0, 4], 1);
  } else if (t === Tile.Trap) {
    rect(img, px + 5, py + 5, TILE - 10, TILE - 10, [122, 96, 64], 1);
    disc(img, cx, cy, TILE * 0.14, [40, 28, 16], 1);
  } else if (t === Tile.Stun) {
    // Hidden in the game apart from a twinkle: shown here, since the catalog is a map.
    disc(img, cx, cy, TILE * 0.4, [192, 192, 64], 0.3);
    disc(img, cx, cy, TILE * 0.14, [240, 240, 110], 1);
  } else if (t === Tile.Transporter) {
    disc(img, cx, cy, TILE * 0.44, [224, 64, 64], 1, TILE * 0.28);
    disc(img, cx, cy, TILE * 0.2, [255, 170, 150], 1);
  } else if (t === Tile.ForceField) {
    rect(img, px, py, TILE, TILE, [255, 96, 32], 0.35);
    for (let i = 0; i < TILE; i += 6) rect(img, px, py + i, TILE, 2, [255, 170, 80], 0.9);
  }
}

function drawLevel(level: LevelData, n: number): Image {
  const img = newImage(level.width * TILE, level.height * TILE);
  for (let y = 0; y < level.height; y++) for (let x = 0; x < level.width; x++) drawTile(img, level, n, x, y);
  for (const g of level.generators) place(img, 'generator', g.x, g.y, 0.95);
  for (const it of level.items) place(img, ITEM_SPRITES[it.kind], it.x, it.y, 0.9);
  for (const m of level.monsters) place(img, m.kind, m.x, m.y, m.kind === 'dragon' ? 2.4 : 1);
  for (const s of level.starts) place(img, 'warrior', s.x, s.y, 1);
  return img;
}

interface LevelSet {
  id: string;
  title: string;
  note?: string;
  texts: string[];
}

function arcadeTexts(dir: string): string[] {
  const index = join(dir, 'index.json');
  if (!existsSync(index)) throw new Error(`${dir} is missing: run the arcade imports first (npm run import:g1, npm run import:g2)`);
  return (JSON.parse(readFileSync(index, 'utf8')) as string[]).map((f) => readFileSync(join(dir, f), 'utf8'));
}

function encodeJpeg(img: Image): Buffer {
  return Buffer.from(jpeg.encode({ width: img.w, height: img.h, data: img.data }, JPEG_QUALITY).data);
}

function escapeHtml(s: string): string {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

/** One set's pictures, and its table for the README. */
function catalogSet(set: LevelSet): string {
  const dir = join(OUT, set.id);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });

  const cells = set.texts.map((text, i) => {
    const n = i + 1;
    const level = parseLevel(text);
    if (isEmptyLevel(level)) populate(level, 7919 + n, n);
    const full = drawLevel(level, n);
    const thumb = shrink(full, THUMB_FILE, Math.round((THUMB_FILE * full.h) / full.w));
    const file = String(n).padStart(3, '0');
    writeFileSync(join(dir, `${file}.jpg`), encodeJpeg(full));
    writeFileSync(join(dir, `${file}-thumb.jpg`), encodeJpeg(thumb));
    const title = levelTitle(n, level.name);
    const alt = escapeHtml(`${set.title} level ${n}${title ? `: ${title}` : ''}`);
    const href = `${dir}/${file}`;
    return `<td align="center"><a href="${href}.jpg"><img src="${href}-thumb.jpg" width="${THUMB_SHOWN}" alt="${alt}"></a><br><sub><b>${n}</b>${title ? ` ${escapeHtml(title)}` : ''}</sub></td>`;
  });

  const rows: string[] = [];
  for (let i = 0; i < cells.length; i += COLUMNS) rows.push(`<tr>\n${cells.slice(i, i + COLUMNS).join('\n')}\n</tr>`);
  const note = set.note ? `\n${set.note}\n` : '';
  console.log(`${set.id}: ${set.texts.length} levels`);
  return `<details open>\n<summary><b>${set.title}</b> (${set.texts.length} levels)</summary>\n${note}\n<table>\n${rows.join('\n')}\n</table>\n</details>`;
}

function main(): void {
  const placed = 'Monsters and items here are one example: the maps only hold walls and exits, and each game places the rest from its own seed.';
  const sets: LevelSet[] = [
    { id: 'builtin', title: 'Built-in', texts: [...BUILTIN_LEVELS] },
    { id: 'gauntlet1', title: 'Gauntlet', note: placed, texts: arcadeTexts('public/levels/gauntlet1') },
    { id: 'gauntlet2', title: 'Gauntlet II', note: placed, texts: arcadeTexts('public/levels/gauntlet2') },
  ];
  const catalog = sets.map(catalogSet).join('\n\n');

  const readme = readFileSync('README.md', 'utf8');
  const start = readme.indexOf(CATALOG_START);
  const end = readme.indexOf(CATALOG_END);
  if (start < 0 || end < start) throw new Error(`README.md needs the markers ${CATALOG_START} and ${CATALOG_END}`);
  writeFileSync('README.md', `${readme.slice(0, start + CATALOG_START.length)}\n${catalog}\n${readme.slice(end)}`);
}

main();
